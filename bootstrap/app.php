            '188.114.96.0/20',
            '190.93.240.0/20',
            '197.234.240.0/22',
            '198.41.128.0/17',
        ];

        $middleware->trustProxies(
            at: $cfCidrs,
            headers: Request::HEADER_X_FORWARDED_FOR
